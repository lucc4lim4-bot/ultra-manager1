// Browser test: Amistoso from the start menu: load a world, pick two teams, play the 2D match, see the result
const { chromium } = require(process.env.PW || 'playwright');
const fs = require('fs'); const path = require('path');
const OUT = process.env.SHOTS || '/tmp/shots';
const dist = path.join(__dirname, '../dist');
const body = fs.readFileSync(path.join(dist, 'index.html'), 'utf8');
fs.writeFileSync(path.join(dist, '_test.html'), `<!doctype html><html><head><meta charset=utf8><meta name=viewport content="width=device-width,initial-scale=1,viewport-fit=cover"><style>:root{color-scheme:light}body{margin:0;font:14px system-ui}img{max-width:100%}[hidden]{display:none!important}</style></head><body>${body}</body></html>`);
(async () => {
  const browser = await chromium.launch();
  const kind = process.env.KIND || 'club';
  const page = await (await browser.newContext(process.env.MOBILE === '1' ? { viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true } : { viewport: { width: 1280, height: 800 } })).newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push('pageerror: ' + e.message + '\n' + (e.stack || '').split('\n').slice(0, 3).join('\n')));
  page.on('console', (m) => { if (m.type() === 'error' && !/fonts\.g/.test(m.text()) && !/Failed to load resource/.test(m.text())) errors.push('console: ' + m.text()); });
  const click = async (sel) => { await page.locator(sel).first().click(); await page.waitForTimeout(250); };
  const shot = (n) => page.screenshot({ path: path.join(OUT, (process.env.MOBILE === '1' ? 'm_' : '') + 'fr_' + kind + '_' + n + '.png') });
  await page.goto('http://localhost:8765/_test.html?debug=1');
  await page.waitForSelector('[data-a="openFriendly"]');
  await click('[data-a="openFriendly"]');
  if (kind === 'national') await click('[data-a="frSet"][data-k="kind"][data-v="national"]');
  await shot('01_setup');
  await click('[data-a="frLoad"]');
  await page.waitForSelector('#fr-q', { timeout: 120000 });
  await shot('02_pick');
  const nameA = kind === 'national' ? 'Brasil' : 'Flamengo', nameB = kind === 'national' ? 'Argentina' : 'Real Madrid';
  await page.fill('#fr-q', nameA); await page.waitForTimeout(300);
  await click('#fr-list [data-a="frPick"]');
  await page.fill('#fr-q', nameB); await page.waitForTimeout(300);
  await click('#fr-list [data-a="frPick"]');
  await shot('03_ready');
  console.log('play enabled:', await page.locator('[data-a="frPlay"]').isEnabled());
  await click('[data-a="frPlay"]');
  await page.waitForSelector('.g2d', { timeout: 20000 });
  await page.waitForTimeout(5000);
  console.log('game state:', await page.evaluate(() => window.__g2d && window.__g2d._G ? window.__g2d._G.state : 'none'));
  await shot('04_playing');
  await page.keyboard.press('p'); await page.waitForTimeout(400);
  await page.locator('.g2d-pause [data-g="sim"]').first().click();
  await page.waitForSelector('[data-a="frAgain"]', { timeout: 30000 }).catch(async (e) => { await shot('05_fail'); console.log('page errors so far:', errors.join('\n') || 'none'); console.log('screen:', await page.evaluate(() => document.body.innerText.slice(0, 300))); throw e; });
  await shot('05_result');
  console.log('result:', (await page.locator('.sc').first().innerText()).replace(/\n/g, ' '));
  await click('[data-a="frAgain"]');
  await page.waitForSelector('.g2d', { timeout: 20000 });
  await page.waitForTimeout(2500);
  console.log('replay state:', await page.evaluate(() => window.__g2d && window.__g2d._G ? window.__g2d._G.state : 'none'));
  console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no errors');
  await browser.close();
})().catch((e) => { console.error('TEST FAILED', e); process.exit(1); });
