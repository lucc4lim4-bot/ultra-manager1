// Browser test: change a player's position from the player screen
const { chromium } = require(process.env.PW || 'playwright');
const fs = require('fs');
const path = require('path');
const OUT = process.env.SHOTS || '/tmp/shots';
const dist = path.join(__dirname, '../dist');
const body = fs.readFileSync(path.join(dist, 'index.html'), 'utf8');
fs.writeFileSync(path.join(dist, '_test.html'), `<!doctype html><html><head><meta charset=utf8><meta name=viewport content="width=device-width,initial-scale=1,viewport-fit=cover"><style>:root{color-scheme:light}body{margin:0;font:14px system-ui}img{max-width:100%}[hidden]{display:none!important}</style></head><body>${body}</body></html>`);
const mobile = process.env.MOBILE === '1';
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext(mobile ? { viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true } : { viewport: { width: 1366, height: 900 } });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
  const pre = (mobile ? 'm_' : '') + 'pos_';
  const shot = async (n) => { await page.screenshot({ path: path.join(OUT, pre + n + '.png') }); };
  const click = async (sel) => { await page.locator(sel).first().click(); await page.waitForTimeout(200); };
  await page.goto('http://localhost:8765/_test.html');
  await page.waitForSelector('[data-a="newCareer"]');
  await click('[data-a="newCareer"]');
  await page.fill('#w-name', 'T'); await page.fill('#w-fav', 'Palmeiras');
  await click('button[type="submit"]');
  await click('[data-a="wizSet"][data-k="era"][data-v="2026"]'); await click('[data-a="wizNext"]'); await click('[data-a="wizNext"]'); await click('[data-a="wizNext"]'); await click('[data-a="wizNext"]');
  await page.waitForSelector('[data-a="pickOffer"]', { timeout: 60000 });
  await click('[data-a="pickOffer"]');
  await page.waitForSelector('.hero-date', { timeout: 120000 });
  await click('[data-a="tab"][data-t="squad"]');
  await click('[data-a="subtab"][data-g="squad"][data-k="hub"]').catch(() => {});
  const rows = page.locator('tr.click[data-a="openPlayer"]');
  await rows.nth(12).click(); await page.waitForTimeout(250);
  await click('[data-a="pPos"]');
  await shot('01_choose');
  console.log('options:', await page.locator('.pos-opt').count());
  await page.locator('.pos-opt').nth(2).click(); await page.waitForTimeout(250);
  await shot('02_player_training');
  console.log('kv:', (await page.locator('.kv').first().innerText()).split('\n').filter((l, i, a) => /Treino/.test(a[i - 1] || '') || /Treino/.test(l)).join(' '));
  await click('[data-a="pPos"]');
  await shot('03_progress');
  await click('.modal-f [data-a="closeModal"]');
  await click('[data-a="closeModal"]');
  await page.waitForTimeout(200);
  console.log('chips:', await page.locator('.chip', { hasText: '⇄' }).count());
  await shot('04_squad');
  console.log(errors.length ? errors.join('\n') : 'no errors');
  await browser.close();
})().catch((e) => { console.error('TEST FAILED', e); process.exit(1); });
