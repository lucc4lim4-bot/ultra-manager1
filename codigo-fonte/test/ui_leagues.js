// Browser test: normal mode with the new leagues — club chooser by region, a career in a new league, tables with
// continental zones, the "outras ligas" list, the Conference League after a few months.
const { chromium } = require(process.env.PW || 'playwright');
const fs = require('fs');
const path = require('path');
const OUT = process.env.SHOTS || '/tmp/shots';
const dist = path.join(__dirname, '../dist');
const body = fs.readFileSync(path.join(dist, 'index.html'), 'utf8');
fs.writeFileSync(path.join(dist, '_test.html'), `<!doctype html><html><head><meta charset=utf8><meta name=viewport content="width=device-width,initial-scale=1,viewport-fit=cover"><style>:root{color-scheme:light}body{margin:0;font:14px system-ui}[hidden]{display:none!important}</style></head><body>${body}</body></html>`);
const CLUB = process.env.CLUB || 'Galatasaray';
(async () => {
  const browser = await chromium.launch();
  const page = await (await browser.newContext({ viewport: { width: 1366, height: 900 } })).newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push('pageerror: ' + e.message + '\n' + (e.stack || '').split('\n').slice(0, 4).join('\n')));
  page.on('console', (m) => { if (m.type() === 'error' && !/fonts\.g/.test(m.text()) && !/Failed to load resource/.test(m.text())) errors.push('console: ' + m.text()); });
  const shot = async (n) => { await page.screenshot({ path: path.join(OUT, 'lg_' + n + '.png') }); };
  const click = async (sel) => { await page.locator(sel).first().click(); await page.waitForTimeout(120); };
  await page.goto('http://localhost:8765/_test.html?debug=1');
  await page.waitForSelector('[data-a="newCareer"]', { timeout: 15000 });
  await click('[data-a="newCareer"]');
  await page.fill('#w-name', 'Ligas Teste');
  await page.keyboard.press('Enter');
  await page.waitForTimeout(100);
  await click('[data-a="wizNext"]'); await click('[data-a="wizNext"]'); await click('[data-a="wizSet"][data-k="mode"][data-v="normal"]'); await click('[data-a="wizNext"]'); await click('[data-a="wizNext"]');
  await page.waitForSelector('[data-a="pickOffer"]', { timeout: 60000 });
  await shot('offers');
  await click('[data-a="anyG"][data-v="sa"]');
  await shot('chooser_sa');
  await page.selectOption('[data-a="anyLg"]', 'COL');
  await page.waitForTimeout(200);
  await shot('chooser_col');
  await click('[data-a="anyG"][data-v="all"]');
  await page.fill('#any-q', CLUB);
  await page.waitForTimeout(300);
  await shot('chooser_search');
  await page.locator('#any-list [data-a="pickOffer"]').first().click();
  await page.waitForSelector('.hero-date', { timeout: 180000 });
  await shot('hub');
  await click('[data-a="tab"][data-t="office"]');
  await shot('table');
  await click('[data-a="otherLeagues"]');
  await page.waitForTimeout(200);
  await shot('other_leagues');
  await click('.modal [data-a="closeModal"]').catch(() => {});
  // a few months later: the Conference League is under way
  await page.evaluate(() => { const um = window.__um; um.fastForward(um.S.date + 110); um.render(); });
  await page.waitForTimeout(300);
  await click('[data-a="subtab"][data-k="cups"]');
  const opts = await page.locator('[data-a="cupSel"] option').allTextContents();
  const uecl = opts.findIndex((t) => /Conference League/.test(t));
  console.log('cups:', opts.length, 'UECL option', uecl);
  if (uecl >= 0) { await page.selectOption('[data-a="cupSel"]', { index: uecl }); await page.waitForTimeout(250); await shot('uecl'); }
  await click('[data-a="subtab"][data-k="table"]');
  await shot('table_later');
  await click('[data-a="subtab"][data-k="results"]');
  await shot('results');
  console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no errors');
  await browser.close();
})().catch((e) => { console.error('TEST FAILED', e); process.exit(1); });
